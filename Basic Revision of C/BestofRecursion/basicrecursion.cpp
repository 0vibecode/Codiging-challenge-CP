#include <iostream>
using namespace std;
void message(){
    cout<<"hello from message"<<endl;
}
void message1(){
    cout<<"hello from message1"<<endl;
}
void message2(){
    cout<<"hello from message2"<<endl;
}
void message3(){
    cout<<"hello from message3"<<endl;
}
void message4(){
    cout<<"hello from message4"<<endl;
}
int main() {
cout << "Basics of recursion" << endl;
message();
message1();
message2();
message3();
message4();

return 0;
}